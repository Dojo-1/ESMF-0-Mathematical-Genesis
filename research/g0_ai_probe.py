"""G0-AI D0: paired, development-only temporal prediction and morphology audit.

The environment is fixed outside the learner. Independent world labels are
sampled after all prediction methods have committed their predictions.
Initial units are role-free; no oracle context or cell labels are provided.
"""
from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
from random import Random
from statistics import mean, stdev

from esmf.telos_substrate_ai import TelosSubstrate

SEEDS = tuple(range(93100, 93112))
FUTURE_RESERVED = tuple(range(94100, 94132))
MODES = ('adaptive', 'plastic_no_growth', 'fixed', 'shuffled')
STEPS = 720
BLOCK = 240


class LaggedTable:
    """Strong hand-featured, fading-memory comparator with privileged lags.

    It sees exactly the same observed cue history and labels, but the input
    lag selection (one and two) is wired in deliberately and unlike the tissue.
    """
    def __init__(self, forgetting: float = .987):
        self.forgetting = forgetting
        self.counts = {(a, b): [1., 1.] for a in (-1, 1) for b in (-1, 1)}
        self.current = None

    def predict(self, history):
        if len(history) < 2:
            self.current = None
            return .5
        self.current = (history[-1][0], history[-2][1])
        a, b = self.counts[self.current]
        return b/(a+b)

    def observe(self, y):
        for values in self.counts.values():
            values[0] = max(.01, values[0]*self.forgetting)
            values[1] = max(.01, values[1]*self.forgetting)
        if self.current is not None:
            self.counts[self.current][int(y)] += 1.


def generate(seed: int, steps: int = STEPS):
    if type(seed) is not int or steps < BLOCK*3:
        raise ValueError('invalid environment')
    rng = Random(seed * 41 + 123)
    history = []
    result = []
    nuisance = -1
    for t in range(steps):
        if rng.random() < .16:
            nuisance = -nuisance
        cues = tuple(1 if rng.random() < .5 else -1 for _ in range(3)) + (nuisance,)
        phase = 1 if BLOCK <= t < 2*BLOCK else 0
        if len(history) < 2:
            p = .5
        else:
            relation = (history[-1][0] == 1) != (history[-2][1] == 1)
            p = .88 if bool(relation) != bool(phase) else .12
        # Labels are generated by the evaluator, never given to the tissue
        # until after every prediction method has committed a probability.
        y = rng.random() < p
        result.append((t, cues, bool(y), phase, p))
        history.append(cues)
    return tuple(result)


def brier(p, y):
    if not (0 <= p <= 1 and math.isfinite(p)):
        raise ValueError('invalid predicted probability')
    return (p-float(y))**2


def run_seed(seed: int):
    if seed not in SEEDS:
        raise ValueError('only registered D0 development seeds')
    stream = generate(seed)
    models = {mode:TelosSubstrate(seed=seed+197, mode=mode)
              for mode in MODES}
    # Initial projections/positions/contacts are equal across all four arms.
    base = models['adaptive']
    initial_contacts = len(base.s.contacts)
    initial_reference = (tuple((u.xyz, u.sensor, u.atp, u.material)
                               for u in base.s.units),
                         tuple((p, e.weight) for p, e in base.s.contacts.items()))
    assert all((tuple((u.xyz, u.sensor, u.atp, u.material)
                      for u in m.s.units),
                tuple((p, e.weight) for p, e in m.s.contacts.items())) ==
               initial_reference for m in models.values())
    ordinary = LaggedTable()
    history=[]
    scores={key:[[], [], []] for key in (*MODES,'lagged_table')}
    cost=[]
    evidence=[]
    for t, cues, label, hidden_phase, pworld in stream:
        predictions={arm: m.predict(cues) for arm,m in models.items()}
        predictions['lagged_table']=ordinary.predict(history)
        # The world label is withheld until every arm commits a prediction.
        if t >= 20:
            for arm,p in predictions.items():
                scores[arm][t//BLOCK].append(brier(p,label))
        for m in models.values():
            m.observe(label)
        ordinary.observe(label)
        history.append(cues)
        if t in (BLOCK-1,2*BLOCK-1,STEPS-1):
            cost.append({arm:m.integrity() for arm,m in models.items()})
        if t in (20,120,240,360,480,600,STEPS-1):
            evidence.append({'t':t,'phase':hidden_phase,
                             'world_probability':pworld,
                             'observed_label':label,
                             'predictions':predictions})
    stats={arm:{'mean':mean(sum(blocks, [])),
                'blocks':[mean(x) for x in blocks]}
           for arm,blocks in scores.items()}
    return {'seed':seed,'scores':stats,'cost':cost,'evidence':evidence,
            'world_events':STEPS,'initial_units':len(base.s.units),
            'initial_contacts':initial_contacts,
            'final_edges':{k:len(m.s.contacts) for k,m in models.items()},
            'active_morphology':{k:m.s.growth_events for k,m in models.items()},
            'all_ledgers_closed':all(m.s.ledger()==(0,0) for m in models.values()),
            'model_label_used_only_by_external_readout':True}


def describe(values):
    xs=list(values)
    mu=mean(xs)
    sem=1.96*stdev(xs)/math.sqrt(len(xs)) if len(xs)>1 else 0.
    return {'n':len(xs),'mean':mu,'descriptive_normal_95':[mu-sem,mu+sem],
            'confirmatory':False}


def run(seeds=SEEDS):
    if tuple(seeds)!=SEEDS:
        raise ValueError('undeclared seed modification would leak development protocol')
    rows=[run_seed(s) for s in seeds]
    summary={arm:describe(r['scores'][arm]['mean'] for r in rows)
             for arm in (*MODES,'lagged_table')}
    paired={arm+'_minus_fixed':describe(r['scores'][arm]['mean']-
                r['scores']['fixed']['mean'] for r in rows)
            for arm in ('adaptive','plastic_no_growth','shuffled')}
    return {'schema':'g0-ai-d0-v1',
            'authority':'M: finite synthetic development only',
            'source_sha':os.getenv('GITHUB_SHA','local-unattributed'),
            'seeds':list(seeds),'steps_per_seed':STEPS,
            'change_points':[BLOCK,2*BLOCK],
            'world':'delayed two-cue relation, hidden phase shifts, noise 0.12',
            'experimental_control_limits':[
                'Only morphology/adaptation arms share all units, sensor projections and input stream.',
                'Morphology is unsupervised but predeclared local rules and event opportunities still constrain what emerges.',
                'Fixed/plastic_no_growth do not expend the same structural material as growing arms; cost-normalized claims forbidden.',
                'Lagged table uses privileged cue-lag selection and is NOT a compute/parameter matched recurrent model.',
                'No independent heldout/biological/hypercomplex advantage established.',
                'Reserved seeds 94100-94131 not touched.'],
            'summary':summary,'paired':paired,'raw':rows}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    d=run()
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(d,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    print('G0_AI_D0_SUMMARY='+json.dumps({k:v for k,v in d.items() if k!='raw'},sort_keys=True))


if __name__=='__main__':
    main()
